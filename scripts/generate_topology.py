#!/usr/bin/env python3
"""Generate a layered, acyclic service graph for the mesh-lab chart.

Output:
  generated/topology.yaml    -> Helm values (services + experiment kinds)
  generated/entrypoints.txt  -> comma separated tier-0 services (k6 targets)

Design notes
- Edges only go from tier k to tier k+1, so the graph is a DAG by construction.
- fake-service calls ALL of its upstreams on every request, so one user request
  fans out along every path. Keep fan-out small (1-2) or the internal call rate
  explodes. The script prints the expected internal calls per user request.
- Every non-entry service has at least one parent, so all of them receive traffic.
"""
import argparse
import random
from pathlib import Path

import yaml

TIER_NAMES = ["fe", "api", "biz", "data", "ext"]
TIER_WEIGHTS = [0.12, 0.22, 0.30, 0.24, 0.12]


def split_sizes(total, weights):
    """Largest-remainder allocation, every tier gets at least 1."""
    raw = [w * total for w in weights]
    sizes = [max(1, int(r)) for r in raw]
    while sum(sizes) < total:
        i = max(range(len(sizes)), key=lambda k: raw[k] - sizes[k])
        sizes[i] += 1
    while sum(sizes) > total:
        i = max(range(len(sizes)), key=lambda k: sizes[k])
        if sizes[i] <= 1:
            break
        sizes[i] -= 1
    return sizes


def build(n, seed, fmin, fmax):
    rnd = random.Random(seed)
    tiers_n = len(TIER_NAMES)
    sizes = split_sizes(n, TIER_WEIGHTS)
    tiers = [
        [f"{TIER_NAMES[t]}-{i + 1:03d}" for i in range(sizes[t])] for t in range(tiers_n)
    ]
    ups = {name: [] for tier in tiers for name in tier}

    for t in range(tiers_n - 1):
        parents, children = tiers[t], tiers[t + 1]
        # 1) coverage: every child gets one parent (least loaded first)
        for child in children:
            least = min(len(ups[p]) for p in parents)
            p = rnd.choice([p for p in parents if len(ups[p]) == least])
            ups[p].append(child)
        # 2) top up parents to the minimum fan-out
        for p in parents:
            want = rnd.randint(fmin, fmax)
            extra = [c for c in children if c not in ups[p]]
            rnd.shuffle(extra)
            while len(ups[p]) < want and extra:
                ups[p].append(extra.pop())
        for p in parents:
            ups[p].sort()
    return tiers, ups


def path_weights(tiers, ups):
    """Expected calls per user request, averaged over a uniformly chosen entrypoint."""
    entries = tiers[0]
    weight = {name: 0.0 for tier in tiers for name in tier}
    for e in entries:
        stack = [(e, 1.0)]
        while stack:
            node, w = stack.pop()
            weight[node] += w / len(entries)
            for u in ups[node]:
                stack.append((u, w))
    return weight


def pick(candidates, count, taken):
    out = []
    for c in candidates:
        if len(out) == count:
            break
        if c not in taken:
            out.append(c)
            taken.add(c)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-n", "--services", type=int, default=50)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--fanout-min", type=int, default=1)
    ap.add_argument("--fanout-max", type=int, default=2)
    ap.add_argument("--canary", type=int, default=2, help="services deployed as Argo Rollouts")
    ap.add_argument("--ab", type=int, default=1, help="services with v1/v2 header A/B")
    ap.add_argument("--mirror", type=int, default=1, help="services with v1/v2 traffic mirroring")
    ap.add_argument("--out", default="generated")
    a = ap.parse_args()

    if a.services < 10:
        ap.error("use at least 10 services")

    tiers, ups = build(a.services, a.seed, a.fanout_min, a.fanout_max)
    weight = path_weights(tiers, ups)

    # experiments go on the busiest services of the middle tiers (never entrypoints)
    middle = [n for t in (1, 2, 3) for n in tiers[t]]
    ranked = sorted(middle, key=lambda n: (-weight[n], n))
    taken = set()
    canary = pick(ranked, a.canary, taken)
    ab = pick(ranked, a.ab, taken)
    mirror = pick(ranked, a.mirror, taken)

    services = []
    for t, tier in enumerate(tiers):
        for name in tier:
            s = {"name": name, "tier": t, "upstreams": ups[name]}
            if name in canary:
                s.update(kind="canary", replicas=2, version="v1", errorRate=0.0)
            elif name in ab or name in mirror:
                s.update(
                    kind="variants",
                    mode="ab" if name in ab else "mirror",
                    v2ErrorRate=0.1,
                    v2LatencyMs=40,
                )
            services.append(s)

    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "topology.yaml").write_text(
        "# generated by scripts/generate_topology.py - do not edit by hand\n"
        + yaml.safe_dump({"services": services}, sort_keys=False)
    )
    (out / "entrypoints.txt").write_text(",".join(tiers[0]))

    edges = sum(len(v) for v in ups.values())
    calls = sum(weight.values())
    print(f"services : {a.services}  tiers: {[len(t) for t in tiers]}")
    print(f"edges    : {edges}")
    print(f"calls/req: ~{calls:.1f} internal calls per user request")
    print(f"canary   : {canary}")
    print(f"ab       : {ab}")
    print(f"mirror   : {mirror}")
    print(f"wrote    : {out}/topology.yaml, {out}/entrypoints.txt")


if __name__ == "__main__":
    main()
